// ==========================================
// 参数类型 → 注入实参
//   aur::Character&  -> 角色实例名（如 "Alice"）
//   aur::Context&    -> aur::detail::context()
// 返回 false 表示不支持，out 填类型名以便报错
// ==========================================
inline bool ClassifyParam(const std::string& type,
                          const std::string& charName,
                          std::string& out)
{
    if (EndsWith(type, "Character")) {
        out = charName;
        return true;
    }
    if (EndsWith(type, "Context")) {
        out = "aur::detail::context()";
        return true;
    }
    out = type;
    return false;
}

// 生成 "c == &Alice || c == &Bob || ..." 这段
// chars 为空时生成 "(void)c" 保证语法完整
inline void WriteCharacterFilter(std::ostream& out,
                                 const std::vector<CharacterConfig>& chars,
                                 const std::string& indent)
{
    if (chars.empty()) {
        out << indent << "(void)c;\n";
        return;
    }
    out << indent << "if (c == &" << chars[0].name;
    for (size_t i = 1; i < chars.size(); ++i)
        out << " || c == &" << chars[i].name;
    out << ") continue;\n";
}

// 生成 index.cpp 时统一使用 aur::detail::xxx
inline bool GenerateIndexCpp(int width, int height,
                             const std::vector<CharacterConfig>& chars,
                             const std::vector<CharFunctions>& charFuncs,
                             const std::vector<int>& sceneList) {
    const fs::path tmpPath = "index.cpp.tmp";
    const fs::path finalPath = "index.cpp";

    std::ofstream out(tmpPath, std::ios::binary | std::ios::trunc);
    if (!out.is_open()) return false;

    out << "// This file is auto-generated by aurinko update\n";
    out << "// Do not edit manually.\n";
    out << "// Edit characters/<name>/<name>.hpp instead.\n\n";

    out << "#include <raylib.h>\n";
    out << "#include <aurinko/init.hpp>\n";
    out << "#include <aurinko/ui_root.hpp>\n";
    out << "#include <aurinko/character.hpp>\n";
    out << "#include <aurinko/coroutine.hpp>\n";
    out << "#include <aurinko/scene.hpp>\n";
    out << "#include <aurinko/text.hpp>\n";
    out << "#include <aurinko/context.hpp>\n";
    out << "#include <aurinko/textbox.hpp>\n";
    out << "#include <aurinko/button.hpp>\n";
    out << "#include <aurinko/panel.hpp>\n";
    out << "#include <aurinko/draw.hpp>\n";
    out << "#include <aurinko/input.hpp>\n";
    out << "#include <aurinko/progress_bar.hpp>\n";
    out << "#include <aurinko/extras/slider.hpp>\n";
    out << "#include <aurinko/extras/plot.hpp>\n";
    out << "#include <aurinko/extras/table.hpp>\n";
    out << "#include \"globals.hpp\"\n\n";

    for (auto& c : chars) {
        out << "#include \"characters/" << c.name << "/" << c.name << ".hpp\"\n";
    }
    out << "\n";

    out << "int main(void) {\n";
    out << "    const int vw = " << width << ";\n";
    out << "    const int vh = " << height << ";\n";
    out << "    aur::detail::virtualScreen.Init(vw, vh, \"Game\");\n\n";

    const int total = static_cast<int>(chars.size());
    for (int i = 0; i < total; i++) {
        auto& c = chars[i];
        const int slot = i + 1;

        out << "    aur::Character " << c.name
            << "(\"" << c.name << "\", "
            << "\"characters/" << c.name << "/" << c.texture << "\", "
            << "{ static_cast<float>(vw) * " << slot << " / " << (total + 1)
            << ", static_cast<float>(vh) / 2 }, "
            << FloatLit(c.scale) << "f, "
            << c.frames << ", "
            << FloatLit(c.frameSpeed) << "f);\n";
    }
    out << "\n";

    for (auto& c : chars) {
        out << "    " << c.name << ".SetScene(" << c.scene << ");\n";
    }
    out << "\n";

    for (auto& c : chars) {
        out << "    aur::detail::sceneManager.Register(&" << c.name << ");\n";
    }
    out << "\n";

    // ---------- 启动角色脚本（按类型注入参数） ----------
    for (auto& cf : charFuncs) {
        int scene = 0;
        for (auto& c : chars) {
            if (c.name == cf.name) { scene = c.scene; break; }
        }

        for (auto& fn : cf.functions) {
            if (fn.isClone) continue;

            std::vector<std::string> args;
            bool ok = true;
            std::string badType;

            for (auto& t : fn.paramTypes) {
                std::string injected;
                if (!ClassifyParam(t, cf.name, injected)) {
                    ok = false;
                    badType = t;
                    break;
                }
                args.push_back(injected);
            }

            if (!ok) {
                out << "    // [aurinko] 跳过 " << cf.name << "::" << fn.name
                    << "：不支持的参数类型 \"" << badType << "\"\n";
                std::cout << "警告: " << cf.name << "::" << fn.name
                          << " 参数类型 \"" << badType
                          << "\" 不受支持，已跳过启动\n";
                continue;
            }

            out << "    aur::detail::scheduler.Start(" << fn.name << "(";
            for (size_t i = 0; i < args.size(); ++i) {
                if (i > 0) out << ", ";
                out << args[i];
            }
            out << "), " << scene << ");\n";
        }
    }
    out << "\n";

    int initialScene = sceneList.empty() ? 0 : sceneList.front();
    out << "    aur::detail::sceneManager.Switch(" << initialScene << ");\n\n";

    out << "    while (!WindowShouldClose()) {\n";
    out << "        float dt = GetFrameTime();\n\n";
    out << "        aur::detail::virtualScreen.ExitFullscreenOnEsc();\n";
    out << "        aur::detail::virtualScreen.EnforceAspectRatio();\n";
    out << "        if (IsKeyPressed(KEY_F11)) aur::detail::virtualScreen.ToggleFullscreen();\n\n";
    out << "        aur::detail::sceneManager.Refresh();\n";
    out << "        aur::detail::sceneManager.Cleanup();\n\n";

    for (auto& c : chars) {
        out << "        " << c.name << ".Update(dt, vw, vh);\n";
    }

    out << "        for (auto* c : aur::detail::sceneManager.GetAll()) {\n";
    out << "            if (c->IsMarkedForDeletion()) continue;\n";
    WriteCharacterFilter(out, chars, "            ");
    out << "            c->Update(dt, vw, vh);\n";
    out << "        }\n\n";

    out << "        aur::detail::virtualScreen.Begin(RAYWHITE);\n\n";
    out << "        aur::detail::scheduler.Update(dt);\n\n";

    for (auto& c : chars) {
        out << "        if (!" << c.name << ".IsAlwaysOnTop()) " << c.name << ".Draw();\n";
    }
    out << "        for (auto* c : aur::detail::sceneManager.GetAll()) {\n";
    out << "            if (c->IsMarkedForDeletion()) continue;\n";
    out << "            if (c->IsAlwaysOnTop()) continue;\n";
    WriteCharacterFilter(out, chars, "            ");
    out << "            c->Draw();\n";
    out << "        }\n";

    for (auto& c : chars) {
        out << "        if (" << c.name << ".IsAlwaysOnTop()) " << c.name << ".Draw();\n";
    }
    out << "        for (auto* c : aur::detail::sceneManager.GetAll()) {\n";
    out << "            if (c->IsMarkedForDeletion()) continue;\n";
    out << "            if (!c->IsAlwaysOnTop()) continue;\n";
    WriteCharacterFilter(out, chars, "            ");
    out << "            c->Draw();\n";
    out << "        }\n";

    for (auto& c : chars) {
        out << "        " << c.name << ".DrawBubble();\n";
    }
    out << "        for (auto* c : aur::detail::sceneManager.GetAll()) {\n";
    out << "            if (c->IsMarkedForDeletion()) continue;\n";
    WriteCharacterFilter(out, chars, "            ");
    out << "            c->DrawBubble();\n";
    out << "        }\n";
    out << "        aur::DrawAllTexts();\n";
    out << "        aur::detail::virtualScreen.End();\n";
    out << "    }\n\n";
    out << "    aur::detail::virtualScreen.Close();\n";
    out << "    return 0;\n";
    out << "}\n";

    out.flush();
    out.close();

    std::error_code ec;
    fs::remove(finalPath, ec);
    fs::rename(tmpPath, finalPath, ec);
    return !ec;
}